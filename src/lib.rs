//! Module utilitaire pour le programme watermark‑remover
//! 
//! Ce module expose les fonctions principales :  
//! * `load_text` – lit un fichier texte  
//! * `clean_watermark` – supprime le watermark ou le normalise  
//! * `write_output` – écrit le texte nettoyé dans un fichier

use std::fs::File;
use std::io::{self, Read, Write};
use std::path::Path;

/// Lit le contenu d’un fichier texte et le renvoie sous forme de chaîne
pub fn load_text<P: AsRef<Path>>(file_path: P) -> io::Result<String> {
    let mut file = File::open(file_path)?;
    let mut contents = String::new();
    file.read_to_string(&mut contents)?;
    Ok(contents)
}

/// Supprime le watermark indiqué (ex. “Generated by GPT‑4”) et normalise les espaces
pub fn clean_watermark(text: &str, pattern: &str) -> String {
    let cleaned = regex::Regex::new(pattern)
        .expect("Invalid regex")
        .replace_all(text, "")
        .to_string();
    let cleaned = regex::Regex::new(r"\s+")
        .expect("Invalid regex")
        .replace_all(&cleaned, " ")
        .trim()
        .to_string();
    cleaned
}

/// Écrit le texte nettoyé dans le fichier de sortie
pub fn write_output<P: AsRef<Path>>(text: &str, output_path: P) -> io::Result<()> {
    let mut file = File::create(output_path)?;
    file.write_all(text.as_bytes())?;
    Ok(())
}
